-- ------------------------------------------------------------
-- 2. 転送する旧URLと転送先を決める
--    ・旧車両が消えている（＝旧URLが今は404）ものだけ。管理画面の「削除済み」から
--      旧車両を戻していた場合は、旧URLにページがあるので転送しない
--    ・今の車両が消えていないものだけ（消えた車へ転送しても404に着くだけ）
--    ・今の車両が売約済みになっていても転送する。車両ページ側で、オーナーズアーカイブに
--      載っていればそちらへさらに転送される
-- ------------------------------------------------------------
create temp table vehicle_redirects_20261116 as
select m.note,
       '/vehicles/' || old_meta.slug as old_path,
       '/vehicles/' || new_meta.slug as new_path
  from vehicle_url_moves_20261116 m
  join vehicles old_vehicle
    on old_vehicle.id = m.old_id
   and old_vehicle.deleted_at is not null
  join seo_metas old_meta
    on old_meta.target_type = 'vehicle'
   and old_meta.target_id = m.old_id
  join vehicles new_vehicle
    on new_vehicle.id = m.new_id
   and new_vehicle.deleted_at is null
  join seo_metas new_meta
    on new_meta.target_type = 'vehicle'
   and new_meta.target_id = m.new_id
 where old_meta.slug <> new_meta.slug;

-- ------------------------------------------------------------
-- 3. 転送を登録する（管理画面でURLを変えたときと同じ手順。lib/seo/redirects.ts）
-- ------------------------------------------------------------

-- 旧URLへの転送が既にあれば（8月以降に管理画面で旧車両のURLを変えていた場合）、
-- 今のページへ直接付け替える。転送の多段化（A→B→C）を避けるため
update redirects r
   set new_path = v.new_path
  from vehicle_redirects_20261116 v
 where r.new_path = v.old_path;

-- 今のURLが、以前の別の転送の「旧URL」として登録されていたら消す（転送のループ防止）
delete from redirects r
 using vehicle_redirects_20261116 v
 where r.old_path = v.new_path;

insert into redirects (old_path, new_path)
select old_path, new_path
  from vehicle_redirects_20261116
on conflict (old_path) do update set new_path = excluded.new_path;

-- ------------------------------------------------------------
-- 4. 結果（登録した転送の一覧）
-- ------------------------------------------------------------
select v.note     as 車両,
       r.old_path as 旧URL,
       r.new_path as 転送先
  from vehicle_redirects_20261116 v
  join redirects r on r.old_path = v.old_path
 order by v.note;

commit;


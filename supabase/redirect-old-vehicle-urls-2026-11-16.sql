-- ============================================================
-- 在庫入れ替え前の車両URLを、同じ車の今のページへ転送するSQL（2026-11-16）
--
-- なぜ必要か:
--   2026-11-07 の在庫入れ替え（replace-inventory-2026-11-07.sql）で、
--   8月から載せていた15台をいったん消し、車選びドットコムの20台を新しいURLで登録し直した。
--   15台のうち13台は同じ車（年式・走行距離が一致。docs/tasks/INVENTORY_IMPORT_2026-11-07.md
--   「グーネットとの重複」）なのに、旧URL（例: /vehicles/daimler-double-six-1990）は
--   転送されずに 404 になっている。Search Console の「見つかりませんでした（404）」の主な原因。
--
--   旧URLは8月から11月7日までサイトマップに載っていて、Googleに登録済み。
--   Instagram や掲載媒体から貼られたリンクもありうる。同じ車の今のページへ恒久転送（301）すれば、
--   旧URLの評価が今のページに引き継がれ、リンクから来た人も車にたどり着ける。
--
--   残り2台（XJ 4.2 ソブリンL 2007年・Xタイプ 2.0 エグゼクティブ 2008年）は
--   今の在庫に無い（売約済みと思われる）ため転送しない。もう無い車のページは 404 のままが正しい
--   （関係の無いページへ転送すると、Googleは「ソフト404」として扱う）。
--
-- 使い方:
--   1. https://supabase.com/dashboard を開く
--   2. プロジェクトを選ぶ
--   3. 左メニューの「SQL Editor」→「New query」
--      ※ 前に使ったタブで「Run」を押し直すと、古い内容のまま実行されます。
--        必ず「New query」で新しいタブを開いてください。
--   4. このファイルの中身を全部コピーして貼り付け、右下の「Run」を押す
--   5. 結果の表に「旧URL → 転送先」が1行ずつ出ます（最大13行）
--      「返された行はありません」と出たら、転送する対象が見つからなかったということです
--
-- 転送は1分以内に効き始めます（サイト側は転送の一覧を1分ごとに読み直すため）。
-- 2回以上実行しても大丈夫です（同じ転送が二重にできることはありません）。
-- 途中でエラーが出た場合は、何も変更されずに元のままです。
-- ============================================================

begin;

-- ------------------------------------------------------------
-- 1. 旧車両と、同じ車の今の車両の組
--    旧: supabase/setup.sql で8月に登録した車（ID c0000000-…）
--    今: 2026-11-07 に車選びドットコムの掲載から登録した車（ID d1000000-…。末尾が掲載ID）
--    URLの文字列ではなく車両IDで突き合わせるので、管理画面でURLを変えていても正しく引ける。
-- ------------------------------------------------------------
create temp table vehicle_url_moves_20261116 (
  old_id uuid primary key,
  new_id uuid not null,
  note   text not null
);


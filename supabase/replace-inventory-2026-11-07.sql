-- メーカー: 同じ名前も同じURL名も無いときだけ作る
insert into manufacturers (name, slug)
select distinct i.manufacturer_name, i.manufacturer_slug
from import_models i
where not exists (
  select 1 from manufacturers m
   where m.slug = i.manufacturer_slug or m.name = i.manufacturer_name
);

-- 同じ名前のメーカーを優先して使い、無ければ同じURL名のものを使う
update import_models i
   set manufacturer_id = (
     select m.id from manufacturers m
      where m.name = i.manufacturer_name or m.slug = i.manufacturer_slug
      order by (m.name = i.manufacturer_name) desc, (m.deleted_at is null) desc
      limit 1);

-- URL名で見つけたメーカーの名前が掲載と違う場合（デイムラー → ディムラー）は、掲載の表記に直す
update manufacturers m
   set name = i.manufacturer_name
  from import_models i
 where m.id = i.manufacturer_id
   and m.name <> i.manufacturer_name
   and not exists (select 1 from manufacturers o where o.name = i.manufacturer_name);

-- 車種: そのメーカーに同じ車種名が無く、同じURL名も無いときだけ作る
-- （管理画面から手入力で作った車種はURL名が違うことがあるため、名前で探す）
insert into models (manufacturer_id, name, slug)
select i.manufacturer_id, i.model_name, i.model_slug
from import_models i
where not exists (
  select 1 from models x
   where x.slug = i.model_slug
      or (x.name = i.model_name and x.manufacturer_id = i.manufacturer_id)
);

update import_models i
   set model_id = (
     select x.id from models x
      where (x.name = i.model_name and x.manufacturer_id = i.manufacturer_id)
         or x.slug = i.model_slug
      order by (x.name = i.model_name and x.manufacturer_id = i.manufacturer_id) desc,
               (x.deleted_at is null) desc
      limit 1);

-- 車両のメーカーは、車種に紐づいているメーカーに揃える
update import_models i
   set manufacturer_id = x.manufacturer_id
  from models x
 where x.id = i.model_id;



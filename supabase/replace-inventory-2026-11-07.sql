-- 今回使うメーカー・車種の一覧（このSQLの中だけで使う一時的な表です）
create temp table import_models (
  model_slug        text primary key,
  model_name        text not null,
  manufacturer_slug text not null,
  manufacturer_name text not null,
  manufacturer_id   uuid,
  model_id          uuid
) on commit drop;


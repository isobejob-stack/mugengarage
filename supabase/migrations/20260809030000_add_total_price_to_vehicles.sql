-- 中古車の価格表示は「車両本体価格」と「支払総額」の2つが必要になる。
-- 従来は price（車両本体価格）の1つしか持っておらず、諸費用込みでいくらになるのかを
-- 構造化して持てなかった（seedでは説明文に文章として併記して逃げていた）。
--
-- 購入検討者が最終的に比較するのは支払総額であり、掲載媒体でも両方の併記が一般的なため、
-- 独立したカラムとして持たせる。
--
-- nullable にしているのは、車両登録の初期段階（現地でのクイック登録など）では
-- 諸費用が確定しておらず、支払総額を出せないことがあるため。
-- 未設定のあいだ、公開サイト側は本体価格のみを表示する。
alter table vehicles
  add column total_price integer;

comment on column vehicles.price is '車両本体価格（税込）';
comment on column vehicles.total_price is '支払総額（税込、諸費用込み）。未確定の場合はNULL';

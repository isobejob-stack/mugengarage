## ジャガー初の量産V8

1996年3月、XK8とともに登場した完全新設計の4.0リッター32バルブV8である。ジャガーにとって**初の量産V8**であり、約290馬力を発生した。1998年にはスーパーチャージャー付きの370馬力仕様がXKRに積まれる。

1997年のX308型XJ8では、直列6気筒とV12を置き換えてXJのエンジンがこのV8に一本化された。3.2リッターが240馬力、4.0リッターが290馬力、スーパーチャージャー付きのXJRが370馬力である。以後、SタイプやX150型XKにも展開されていく。

2009年1月には新設計の5.0リッター（AJ133）が登場した。筒内直接噴射とトルク駆動の可変バルブタイミングを備え、自然吸気385PS、スーパーチャージャー付きで510PSを発生する。AJ-V8にとって3世代目にあたる。

## 直列6気筒との違い

ブロックは**アルミ合金**である。8気筒を鋳鉄で作ると前が重くなりすぎるため、素材で軽さを稼いでいる。

したがって性格が違う。直6の鋳鉄ブロックが「頑丈さ」なら、こちらは**滑らかさと静けさ**が身上になる。回転の上がり方に段が無く、速度が出ていることに気づきにくい。

## 所有するということ

アルミブロックは熱に弱い。**冷却系の管理が、そのまま寿命を決める**と考えていただきたい。水温計から目を離さないこと、水回りは症状が出る前に替えること。この2点を守れるかどうかで、同じ年式でも状態がまったく変わってくる。

「丈夫な直6か、滑らかなV8か」——どちらが良いという話ではなく、付き合い方が変わるという話である。実車に乗って選んでいただきたい。

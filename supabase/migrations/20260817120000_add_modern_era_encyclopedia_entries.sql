## ジャガーがつくった、いちばん小さい4ドア

2000年11月に詳細が公表され、2001年3月のジュネーブ・ショーで実車が披露された。ジャガーにとって初のコンパクトな四ドアサルーンである。生産は全面改装されたマージーサイドのヘイルウッド工場が担った。

搭載されたのは2.5リッターと3.0リッター（231馬力）のAJ-V6で、いずれも「トラクション4」と名付けられた**フルタイム四輪駆動を標準装備**する。フォード・モンデオと基本設計を共有する点は当時から議論を呼んだが、四輪駆動を標準としたのはジャガーとして初めてのことだった。

2003年には2.0リッターのターボディーゼルが設定され、これがジャガー初のディーゼル搭載車となる。2004年初頭にはエステート（ステーションワゴン）が加わった。ジャガーが量産車として手がけた初のワゴンである。

## 乗るとどうか

**寸法が日本の道に合っている。** ジャガーに乗りたいが車庫と道幅が心配、という方の不安をほぼ解消する大きさである。

それでいて中に座れば、木と革のジャガーの室内がある。ここが他のコンパクトセダンとの決定的な違いで、Xタイプを選ぶ方の多くはこの一点を理由に挙げられる。

四輪駆動は、雪の降る地域や雨の高速道路で効いてくる。おおらかに走らせたときの安定感は、この大きさの車としては際立っている。

## 所有するということ

**初めてのジャガーとして最も現実的な1台**だと考えている。部品の入手性、整備のしやすさ、日常での扱いやすさのいずれも、この年代のジャガーの中では良い部類に入る。

一方で、「モンデオと兄弟」という出自を気にされる方は一定数いらっしゃる。実車に乗っていただくと印象が変わることが多いので、まず座って、走らせてから判断されることをお勧めしている。

四輪駆動ゆえに駆動系の点検箇所が前輪駆動車より多い。距離を走った個体では、その部分の整備履歴を確認したい。

## 見分け方

エステートは後半のみの設定。ディーゼルは前輪駆動・マニュアル変速機のみの設定で、四輪駆動のガソリン車とは性格が異なる。

## 35年ぶりに戻ってきた名前

1998年10月のバーミンガム・モーターショーで、1963〜68年のSタイプ以来となる名跡を継ぐ中型サルーンが公開された。造形はジェフ・ローソンによるもので、丸型4灯と縦格子グリルに往年のMark 2やSタイプの面影を宿している。発売は1999年1月。

車台はフォード傘下のDEWプラットフォームで、リンカーンLSと共有された。この点は当時から議論を呼んだが、生産はキャッスル・ブロムウィッチのジャガー自身の工場が担当している。エンジンは3.0リッターV6と4.0リッターV8。

2004年半ば、イアン・カラムの監修で大がかりな手直しを受けた。ボディ中央部とルーフはそのままに、前後の造形を引き締め、丸みの強かった初期型から精悍な姿へ改められている。内装のレイアウトも見直された。同年には2.7リッターV6ターボディーゼルが加わっている。

## 乗るとどうか

XJより一回り小さく、Xタイプより明確に大きい。**日本の道でもてあまさず、それでいて長距離で疲れない**という、この店で最も勧めやすい寸法にある。

丸型4灯のフロントマスクは、実車で見ると写真より低く構えて見える。内装はウッドとレザーで、この年代のジャガーらしい室内が保たれている。

## 所有するということ

**前期型と後期型で印象がまったく違う車**である。中古車として出会うときは、まずどちらかを確かめていただきたい。丸みの強い初期型を「古典的で良い」と取るか「締まりがない」と取るかは、はっきり好みが分かれる。

年式的に電装まわりの手入れが必要になる時期に入っている。ジャガー専門で見ている店とそうでない店とで、状態の差が出やすい年代でもある。

## 見分け方

2004年の手直しで前後の造形が変わっているため、フロントバンパーとテールランプの形で前期・後期を判別できる。1963年の「Sタイプ／420」とは別の車なので、図鑑では項目を分けている。

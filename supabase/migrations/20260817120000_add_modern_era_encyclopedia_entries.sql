## Eタイプの役目を、現代の技術で引き継いだ車

1996年3月のジュネーブ・ショーで公開されたXK8（開発コードX100）は、21年続いたXJSの後継として登場した。同じジュネーブでEタイプがデビューしてから35年後という舞台選びに、この車の位置づけが表れている。

心臓は完全新設計の4.0リッター32バルブV8「AJ-V8」。ジャガーにとって初の量産V8であり、約290馬力を発生した。1998年にはスーパーチャージャーを備えた370馬力のXKRが加わり、以後「R」がジャガーの高性能仕様を示す記号として定着していく。

2005年9月、9年続いたX100は**X150型XK**へと世代交代する。デザイン責任者イアン・カラムは「Eタイプの流儀を現代に置き換えた」と語った。車体はXJに続く接着・リベット結合のアルミモノコックで、先代より約91kg軽い。

## 乗るとどうか

限界を攻めるスポーツカーではない。**長い距離を、速く、静かに、優雅に移動するための車**である。

低い着座位置と長いボンネット、そして踏んだときに前に出る大きなトルク。高速道路に乗ってしまえば、目的地までの時間が驚くほど短く感じられる。2+2の後席は緊急用に近いが、荷物置きとして実用になる寸法があり、二人で長旅に出るには十分な積載を確保している。

## 所有するということ

**X100（1996〜2005年）とX150（2005年〜）では、性格がかなり違う。**

X100は鋼板の車体で、内装の木と革の量が多く、旧いジャガーの雰囲気を強く残す。年式的にも手を入れる前提で選ぶ個体である。X150はアルミ車体で軽く、現代の車として日常的に使える。旧車らしさを求めるならX100、道具として使いたいならX150、という選び方になる。

いずれもAJ-V8はアルミブロックのため、**冷却系の管理が寿命を左右する**。水回りは症状が出る前に替えるものと考えていただきたい。クーペは幌の心配が無く、コンバーチブルは幌の状態と作動の確認が最優先になる。

## 見分け方

XKRは、メッシュのグリルとボンネットのルーバーが標準型との違い。X100とX150は一目で分かる別物で、X150は丸みが減り、フロントの造形が薄く鋭い。

## AJ6を鍛え直した、最後の直列6気筒

1994年9月のX300型XJとともに登場した、AJ6の大幅改良版である。3.2リッターが216馬力、4.0リッターが246馬力。**鍛造クランクシャフト**と統合された電子制御を得て、信頼性と洗練を大きく高めた。

最上級には、XJ史上初となるスーパーチャージャー付き4.0リッターを積むXJRが据えられている。

そして1997年、X308型XJ8への移行にともなって直列6気筒はV8に置き換えられた。**AJ16はジャガー最後の直列6気筒**であり、XKエンジン以来続いた系譜の終着点にあたる。

## 所有するということ

ブロックは**鋳鉄**である。重い代わりに熱で歪みにくく、摩耗に強く、修理が効く。距離を走った個体でも腰下が生きていることが多いのは、この素材によるところが大きい。

長く乗ることを前提に選ぶなら、この点は大きな安心材料になる。当店がX300型のXJをお勧めすることが多い理由のひとつでもある。

暖機をして、月に一度は走らせ、冷却系を先手で替える。これだけ守っていれば、素材の丈夫さが効いてくる。

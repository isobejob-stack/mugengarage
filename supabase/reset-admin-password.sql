-- 管理画面にログインできなくなったときの パスワード再設定用SQL
-- 版数: v1
--
-- 使い方:
--   1. https://supabase.com/dashboard を開く
--   2. プロジェクトを選ぶ
--   3. 左メニューの「SQL Editor」→「New query」
--      ※ 前に使ったタブで「Run」を押し直すと、古い内容のまま実行されます。
--        必ず「New query」で新しいタブを開いてください。
--   4. 下の【手順1】をコピーして貼り付け →「Run」→ 登録済みのメールアドレスを確認
--   5. 【手順2】をコピーして貼り付け、2箇所を書き換えて →「Run」
--   6. https://（サイトのURL）/admin/login から新しいパスワードでログイン
--
-- 何度実行しても問題ありません。
-- 途中でエラーが出たら、そのメッセージをそのまま伝えてください。
-- ============================================================


-- ============================================================
-- 【手順1】いま登録されている管理者アカウントを確認する
--
--   「どのメールアドレスで登録したか」を思い出すための確認用です。
--   何も変更しません。安心して実行してください。
--
--   ・email              … ログインに使うメールアドレス
--   ・name               … 管理者名
--   ・last_sign_in_at    … 最後にログインできた日時
--   ・banned_until       … 値が入っていたらアカウントが停止中（手順2で解除されます）
--   ・email_confirmed_at … 空だとメール未確認でログインできない（手順2で解除されます）
--
--   ここで1行も表示されない場合は、そもそも管理者アカウントが
--   作られていません。ファイル末尾の【補足】を見てください。
-- ============================================================

select
  u.email,
  a.name,
  u.last_sign_in_at,
  u.banned_until,
  u.email_confirmed_at
from auth.users u
  left join admin_users a on a.id = u.id
order by u.created_at;


-- ============================================================
-- 【手順2】パスワードを新しいものに設定し直す
--
--   下の2箇所だけを書き換えてから実行してください。
--
--     ・'ここに新しいパスワード' → これから使いたいパスワード
--     ・'ここにメールアドレス'   → 手順1で確認したメールアドレス
--
--   シングルクォート（'）は消さずに、中身だけを書き換えます。
--   例: crypt('Jaguar2026!garage', gen_salt('bf'))
--
--   パスワードは推測されにくいものにしてください（12文字以上を推奨）。
--   このファイルに実際のパスワードを書き込んで保存・コミットしないこと。
--
--   ついでに次の2つも直します（ログインできない原因になりがちなため）。
--     ・メール未確認の状態 → 確認済みにする
--     ・アカウント停止の状態 → 解除する
-- ============================================================

update auth.users
set
  encrypted_password = crypt('ここに新しいパスワード', gen_salt('bf')),
  email_confirmed_at = coalesce(email_confirmed_at, now()),
  banned_until = null,
  updated_at = now()
where email = 'ここにメールアドレス';


-- 実行後に「UPDATE 1」と表示されれば成功です。
-- 「UPDATE 0」の場合はメールアドレスが一致していません。手順1をやり直してください。



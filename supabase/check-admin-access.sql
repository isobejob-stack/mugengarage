-- ============================================================
-- 【手順1】いま管理画面に入れる人を確認する（変更しません）
--
--   結果の見方:
--     ・管理画面に入れますか = 「入れます」    … そのまま本番に出して大丈夫
--     ・管理画面に入れますか = 「入れません」  … 【手順2】で登録してください
--
--   ★ 1行も「入れます」が無い場合、本番に出すと誰も管理画面に
--     入れなくなります。必ず【手順2】を先に実行してください。
-- ============================================================

select
  u.email                       as メールアドレス,
  a.name                        as 管理者名,
  case when a.id is null
       then '入れません（admin_users に未登録）'
       else '入れます' end      as 管理画面に入れますか,
  u.last_sign_in_at             as 最終ログイン,
  u.id                          as UID
from auth.users u
  left join admin_users a on a.id = u.id
order by u.created_at;


